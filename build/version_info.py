"""Generate a PyInstaller VERSIONINFO resource file for the Windows EXE.

Why this exists
---------------
A PyInstaller build with no version resource produces an EXE whose
CompanyName / ProductName / FileDescription / FileVersion are all blank. An
unsigned binary with no identity metadata is exactly the shape that Windows
Defender's generic machine-learning heuristics (``Trojan:Win32/Wacatac.B!ml``)
and SmartScreen punish hardest. Populating real metadata measurably reduces
false positives and makes the file inspectable via right-click -> Properties.

The version is never hardcoded here. It is resolved from, in order:

1. ``UPS_LABEL_CROPPER_VERSION`` (set by CI from the release-please tag).
2. The installed distribution metadata (``pyproject.toml`` version).
3. ``0.0.0`` for an unmanaged local build.

PyInstaller ``exec()``s the ``.spec`` file without importing the project, so
this module is imported by path from ``UPS-Label-Cropper.spec``.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

APP_NAME = "UPS Label Cropper"
EXE_NAME = "UPS-Label-Cropper"
COMPANY_NAME = "twilsonco"
DESCRIPTION = "Auto-rotates and scales UPS shipping labels for thermal printers"
WEBSITE = "https://github.com/twilsonco/UPS-Label-Cropper"
YEAR = "2026"

_NUMERIC_VERSION_RE = re.compile(r"^\d+(?:\.\d+){0,3}")


def resolve_version() -> str:
    """Return the version string to embed in the EXE."""
    env_version = os.environ.get("UPS_LABEL_CROPPER_VERSION", "").strip().lstrip("vV")
    if env_version:
        return env_version

    try:
        from importlib.metadata import version

        return version("ups-label-cropper")
    except Exception:
        return "0.0.0"


def msvs_version(version_str: str) -> tuple[int, ...]:
    """Return the numeric ``msvs_version`` quad for a version string.

    Windows version resources only accept integers, so pre-release suffixes
    (``1.6.0-beta.1`` -> ``(1, 6, 0, 0)``) are dropped while the full string is
    still shown in the human-readable ``FileVersion`` field.
    """
    match = _NUMERIC_VERSION_RE.match(version_str)
    parts = tuple(int(p) for p in match.group(0).split(".")) if match else (0, 0, 0)
    return parts + (0,) * (4 - len(parts))


def render(version_str: str) -> str:
    """Return the contents of a PyInstaller version-info file.

    PyInstaller loads this file with ``eval()`` inside
    ``PyInstaller.utils.win32.versioninfo`` (see
    ``load_version_info_from_text_file``). Two consequences, both easy to get
    wrong:

    * The file must be a **single expression** -- no imports, no assignments.
      The ``VSVersionInfo``/``FixedFileInfo``/``StringFileInfo``/``StringTable``/
      ``StringStruct``/``VarFileInfo``/``VarStruct`` names are already bound in
      the eval namespace.
    * The translation class is ``VarStruct`` (there is no ``Var``), and
      ``StringStruct`` entries must be nested inside a ``StringTable``.
    """
    quad = msvs_version(version_str)

    string_fields = [
        ("CompanyName", COMPANY_NAME),
        ("FileDescription", DESCRIPTION),
        ("FileVersion", version_str),
        ("InternalName", EXE_NAME),
        ("LegalCopyright", f"Copyright (c) {YEAR} {COMPANY_NAME}"),
        ("OriginalFilename", f"{EXE_NAME}.exe"),
        ("ProductName", APP_NAME),
        ("ProductVersion", version_str),
        ("Comments", f"Source: {WEBSITE}"),
    ]
    structs = ",\n        ".join(
        f"StringStruct({name!r}, {value!r})" for name, value in string_fields
    )

    return f"""# UTF-8
# Auto-generated by build/version_info.py -- DO NOT EDIT.
# Version comes from $UPS_LABEL_CROPPER_VERSION (falls back to package metadata).
# Must remain a single evaluable expression; see the module docstring.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={quad!r},
    prodvers={quad!r},
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        {structs},
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [0x409, 1200])]),
  ]
)
"""


def write(path: str | Path, version_str: str | None = None) -> Path:
    """Write the version-info resource to ``path`` and return it."""
    version_str = version_str or resolve_version()
    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(render(version_str), encoding="utf-8")
    return dest


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", default="build/version_info.txt")
    args = parser.parse_args()
    out = write(args.output)
    print(f"Wrote {out} (version {resolve_version()})")
